import { mkdir, readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const SOURCE_SHA = '8590ae556bfdb69fdb967941cc4bf43f7f4c2902';
const SOURCE_URL = `https://raw.githubusercontent.com/hingston/japanese/${SOURCE_SHA}/44998-japanese-words.txt`;
const __dirname = path.dirname(fileURLToPath(import.meta.url));
const outputPath = path.resolve(__dirname, '../src/utils/shareCodecModelV1.ts');

const utf8Length = (value) => Buffer.byteLength(value, 'utf8');

const buildModel = (corpus) => {
  const charScore = new Map();
  const ngramScore = new Map();

  for (let rank = 0; rank < corpus.length; rank += 1) {
    const chars = [...corpus[rank]];
    const weight = 1 / Math.pow(rank + 10, 0.68);

    chars.forEach((char) => {
      charScore.set(char, (charScore.get(char) ?? 0) + weight);
    });

    for (let size = 2; size <= 5; size += 1) {
      for (let start = 0; start + size <= chars.length; start += 1) {
        const token = chars.slice(start, start + size).join('');
        if (utf8Length(token) <= size) continue;
        ngramScore.set(
          token,
          (ngramScore.get(token) ?? 0) + weight * (utf8Length(token) - 1),
        );
      }
    }
  }

  const chars = [...charScore.entries()]
    .sort((a, b) => b[1] - a[1])
    .map(([token]) => token)
    .slice(0, 4096);

  const subwords = [...ngramScore.entries()]
    .sort((a, b) => b[1] - a[1])
    .map(([token]) => token)
    .slice(0, 8192);

  return { corpus, chars, subwords };
};

const isCurrent = async () => {
  try {
    const current = await readFile(outputPath, 'utf8');
    return current.includes(`MODEL_SOURCE_SHA = ${JSON.stringify(SOURCE_SHA)}`);
  } catch {
    return false;
  }
};

if (await isCurrent()) {
  console.log(`share codec model is current (${SOURCE_SHA.slice(0, 12)})`);
  process.exit(0);
}

const response = await fetch(SOURCE_URL);
if (!response.ok) {
  throw new Error(`Failed to download share codec corpus: ${response.status}`);
}

const corpus = (await response.text())
  .split(/\r?\n/u)
  .map((word) => word.trim())
  .filter(Boolean);

if (corpus.length !== 44998) {
  throw new Error(`Unexpected corpus size: ${corpus.length}`);
}

const model = buildModel(corpus);
const source = [
  '/* eslint-disable */',
  '// Generated by scripts/generate-share-codec-model.mjs.',
  '// ABI WARNING: changing this data requires a new URL prefix/codec version.',
  "import type { ShareCodecModelV1 } from './shareCodecV3.ts';",
  `export const MODEL_SOURCE_SHA = ${JSON.stringify(SOURCE_SHA)};`,
  `export const SHARE_CODEC_MODEL_V1: ShareCodecModelV1 = ${JSON.stringify(model)};`,
  '',
].join('\n');

await mkdir(path.dirname(outputPath), { recursive: true });
await writeFile(outputPath, source, 'utf8');
console.log(`generated ${outputPath}`);
console.log(
  `corpus=${model.corpus.length}, chars=${model.chars.length}, subwords=${model.subwords.length}`,
);
